# ====================
# String
# ====================

# Definition:

# - String is a sequence of characters.
# - It is enclosed within Single (' '), Double (" ") or Triple (''' ''') quotation marks.

# Single Quotation Mark
# my_name = 'Rohan'
# print(my_name)

# Double Quotation Mark
# my_object = "Rohan's watch"
# print(my_object)

# Triple Quotation Mark
# my_sentence = '''It was a fantastic topic "Hostel Life"'''
# print(my_sentence)
#____________________________________________________________________________________

# =====================
#  String Indexing
# =====================

# Definition:

# - Indexing is used to access individual characters from a string.
# - In Python, indexing starts from 0.

# ============================
#  Positive Indexing
# ============================

# - Positive indexing starts from left to right.
# - It starts from 0.

